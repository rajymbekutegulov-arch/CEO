let currentLang = 'ru';

export function getLang() {
  return currentLang;
}

export function setLang(lang, { persist = true } = {}) {
  currentLang = lang === 'kz' ? 'kz' : 'ru';
  if (persist) {
    try {
      localStorage.setItem('ent8:lang', currentLang);
    } catch { /* storage may be unavailable */ }
  }
  document.documentElement.lang = currentLang === 'kz' ? 'kk' : 'ru';
  return currentLang;
}

export function initialLang() {
  try {
    const saved = localStorage.getItem('ent8:lang');
    if (saved === 'ru' || saved === 'kz') return saved;
  } catch { /* ignore */ }
  return 'ru';
}

/** Translate an interface key with {placeholder} interpolation. */
export function t(key, vars) {
  const entry = dict[key];
  if (!entry) return key;
  let text = entry[currentLang] || entry.ru || key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** Pick a localized value from a {ru, kz} content object. */
export function pick(value, lang = currentLang) {
  if (value == null) return '';
  if (typeof value === 'string') return value;
  return value[lang] || value.ru || value.kz || '';
}

export function isDictKey(key) {
  return Object.hasOwn(dict, key);
}

